"""Derive the ITOR submission from main.tex, in the journal's own class.

The guide is explicit: "Submissions in LaTeX must be prepared using ITOR's LaTeX
macro package... Submissions in disagreement with ITOR's LaTeX macro package
will be returned to the authors for reformatting." The paper is written in
elsarticle, which is Elsevier's, so this converts it rather than keeping a
second copy of the manuscript that could drift from the first.

Only the front matter and the preamble differ between the two. The body is
carried across untouched, so every number in the submitted PDF is the same macro
generated from the same run record, and the gate that checks main.tex covers
this file's content too.

What changes, and why:

  documentclass   itor, which sets its own paper size, margins and spacing, so
                  the geometry and setspace packages come out
  front matter    elsarticle's frontmatter block becomes the class's \\title,
                  \\author[running], \\affil, \\email, \\thanks, \\keywords
  keywords        semicolon separated, as the class wants, not \\sep
  bibliography    itor.bst, which produces the Harvard style the guide prints
                  examples of
  line numbers    removed; the review option was for referees of the preprint
  graphics        the extension comes off, so the same source resolves a PDF
                  under pdflatex and an EPS under a PostScript route

Usage: python or_journal/make_itor.py
"""
import io
import os
import re
import shutil
import subprocess

SRC = "paper_or/main.tex"
OUT = "paper_or/itor.tex"
PKG = "paper_or/itor_template/itor"
NEEDED = ("itor.cls", "itor.bst")

PREAMBLE = r"""% Generated by or_journal/make_itor.py from main.tex -- do not edit by hand.
% The manuscript in the journal's own class, which the guide requires for any
% LaTeX submission. The body is carried across from main.tex unchanged.
\documentclass{itor}

\usepackage{natbib}
\usepackage{amsmath,amssymb}
\usepackage{booktabs}
\usepackage{url}
\urlstyle{same}
\input{numbers}

\jname{International Transactions in Operational Research}
\jvol{XX}
\jyear{20XX}

\begin{document}

"""


def front(tex: str) -> str:
    """The class's front matter, built from what elsarticle's block carries."""
    title = re.search(r"\\title\{(.*?)\}\s*\n", tex, re.S).group(1).strip()
    abstract = re.search(r"\\begin\{abstract\}\n(.*?)\n\\end\{abstract\}", tex, re.S).group(1)
    kw = re.search(r"\\begin\{keyword\}(.*?)\\end\{keyword\}", tex, re.S).group(1)
    keywords = "; ".join(k.strip() for k in kw.split(r"\sep") if k.strip())

    authors, affils, emails = [], [], []
    for m in re.finditer(r"\\author\[(\d+)\]\{(.*?)\}\n\\ead\{(.*?)\}", tex):
        tag, name, mail = m.group(1), m.group(2), m.group(3)
        star = r",$\ast$" if r"\corref" in name else ""
        name = re.sub(r"\\corref\{[^}]*\}", "", name).strip()
        mark = "abcdefgh"[int(tag) - 1]
        authors.append(f"{name}" + r"\affmark{" + mark + star + "}")
        short = name.split()[0][0] + ". " + name.split()[-1]
        emails.append(f"{mail} [{short}]")
    for m in re.finditer(r"\\affiliation\[(\d+)\]\{(.*?)\}\n", tex):
        tag, body = m.group(1), m.group(2)
        fields = dict(re.findall(r"(\w+)=\{([^}]*)\}", body))
        parts = [fields.get(k, "") for k in
                 ("organization", "addressline", "city", "postcode", "state", "country")]
        mark = "abcdefgh"[int(tag) - 1]
        affils.append(r"\affil{\affmark{" + mark + "}" +
                      ", ".join(p for p in parts if p) + "}")
    assert authors and affils and emails, "the front matter did not parse"

    corr = next((a for a in authors if r"\ast" in a), authors[0])
    corr_mail = emails[authors.index(corr)].split(" [")[0]
    running = re.sub(r"\\affmark\{[^}]*\}", "", authors[0]).split()[-1]

    return ("\\title{" + title + "}\n\n"
            + "\\author[" + running + "]{" + " and ".join(authors) + "}\n\n"
            + "\n".join(affils) + "\n"
            + "\\email{" + "; ".join(emails) + "}\n\n"
            + "\\thanks{\\affmark{$\\ast$}Author to whom all correspondence should be "
              "addressed (e-mail: " + corr_mail + ").}\n\n"
            + "\\begin{abstract}\n" + abstract + "\n\\end{abstract}\n\n"
            + "\\keywords{" + keywords + "}\n\n\\maketitle\n")


def main() -> int:
    tex = io.open(SRC, encoding="utf-8").read()
    for f in NEEDED:
        src = os.path.join(PKG, f)
        if not os.path.exists(src):
            print(f"missing {src}; extract the journal's macro package there first")
            return 1
        shutil.copy2(src, os.path.join("paper_or", f))

    body = tex.split(r"\end{frontmatter}", 1)[1]
    body = body.replace(r"\linenumbers", "").lstrip("\n")
    body = body.replace(r"\bibliographystyle{elsarticle-harv}",
                        r"\bibliographystyle{itor}")
    # the extension comes off so one source serves both output routes
    body = re.sub(r"(\\includegraphics\[[^\]]*\]\{figures/\w+)\.pdf\}", r"\1}", body)
    assert ".pdf}" not in body, "a graphics extension survived"

    io.open(OUT, "w", encoding="utf-8").write(PREAMBLE + front(tex) + body)

    # the aux from a previous class carries commands this one does not define,
    # and latexmk reads it before the preamble runs, so it must go first
    subprocess.run(["latexmk", "-C", "itor"], cwd="paper_or",
                   capture_output=True, text=True)
    for _ in range(3):
        subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", "itor"],
                       cwd="paper_or", capture_output=True, text=True)
    pdf = "paper_or/itor.pdf"
    if not os.path.exists(pdf):
        print("itor.pdf did not build; see paper_or/itor.log")
        return 1
    import fitz
    d = fitz.open(pdf)
    refs = next((i + 1 for i, p in enumerate(d)
                 if re.search(r"\nReferences", p.get_text())), None)
    print(f"wrote {OUT} and {pdf}")
    print(f"PAGES: {d.page_count}   references begin on page {refs}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
