"""Derive the Financial Innovation manuscript from main.tex.

The journal takes LaTeX and encourages, but does not require, Springer
Nature's own template, so this builds against the standard article class and
satisfies every requirement the guide actually states: double-line spacing,
line and page numbering, no page breaks, author-year citations, figure titles
and legends carried in the manuscript rather than in the graphics.

Like make_itor.py this derives everything from main.tex so the two cannot
drift. Nothing here is edited by hand.
"""
import io
import os
import re
import subprocess
import sys

SRC = "paper_or/main.tex"
OUT = "paper_or/fininnov.tex"
STEM = "fininnov"

PREAMBLE = r"""% Generated by or_journal/make_fininnov.py from main.tex -- do not edit by hand.
\documentclass[12pt]{article}

\usepackage[utf8]{inputenc}
\usepackage[T1]{fontenc}
\usepackage{times}
\usepackage[a4paper,margin=1in]{geometry}
\usepackage{setspace}
\usepackage{lineno}
\usepackage{amsmath,amssymb}
\usepackage{booktabs}
\usepackage{graphicx}
\usepackage{natbib}
\usepackage{url}
\urlstyle{same}
\bibpunct{(}{)}{;}{a}{}{,}
\usepackage[hidelinks]{hyperref}
\input{numbers}

% The guide asks for double-line spacing and for line and page numbering.
\doublespacing
\linenumbers

\begin{document}

"""


def frontmatter(tex: str) -> str:
    """Rebuild the elsarticle frontmatter as a plain article frontmatter."""
    head = tex.split(r"\end{frontmatter}", 1)[0]

    title = re.search(r"\\title\{(.+?)\}\s*\n", head, re.S).group(1).strip()

    # the name carries \corref{...}, so the group must span one nested brace
    authors = re.findall(r"\\author\[(\d+)\]\{((?:[^{}]|\{[^{}]*\})*)\}", head)
    emails = re.findall(r"\\ead\{([^}]+)\}", head)
    affils = dict(re.findall(r"\\affiliation\[(\d+)\]\{(.+?)\}\s*\n", head, re.S))
    assert authors and affils, "frontmatter did not parse"
    assert len(emails) == len(authors), "one email per author expected"

    def plain(aff: str) -> str:
        """Flatten organization={...}, addressline={...} into one address."""
        parts = re.findall(r"\w+=\{([^}]*)\}", aff)
        return ", ".join(p.strip() for p in parts if p.strip())

    names = []
    for i, (mark, raw) in enumerate(authors):
        name = re.sub(r"\\corref\{[^}]*\}", "", raw).strip()
        star = r"$^{*}$" if i == 0 else ""
        names.append(f"{name}$^{{{mark}}}${star}")

    lines = [r"\title{" + title + "}", r"\date{}",
             r"\author{" + r" \and ".join(names) + "}",
             r"\maketitle", ""]

    lines.append(r"\begin{center}\small")
    for mark in sorted(affils):
        lines.append(r"$^{" + mark + r"}$ " + plain(affils[mark]) + r" \\")
    lines.append(r"\vspace{0.5em}")
    for (mark, raw), mail in zip(authors, emails):
        name = re.sub(r"\\corref\{[^}]*\}", "", raw).strip()
        lines.append(name + r": \texttt{" + mail.replace("_", r"\_") + r"} \\")
    lines.append(r"$^{*}$ Corresponding author.")
    lines.append(r"\end{center}")
    lines.append("")

    abstract = re.search(r"\\begin\{abstract\}(.*?)\\end\{abstract\}",
                         head, re.S).group(1).strip()
    lines += [r"\begin{abstract}", r"\noindent " + abstract,
              r"\end{abstract}", ""]

    kw = re.search(r"\\begin\{keyword\}(.*?)\\end\{keyword\}", head, re.S)
    if kw:
        words = [w.strip() for w in kw.group(1).split(r"\sep") if w.strip()]
        lines += [r"\noindent\textbf{Keywords:} " + "; ".join(words), ""]

    # A JEL-free fintech journal still wants the body to start on the same page.
    return "\n".join(lines) + "\n"


def main() -> int:
    tex = io.open(SRC, encoding="utf-8").read()

    body = tex.split(r"\end{frontmatter}", 1)[1]
    # linenumbers is switched on in the preamble instead
    body = body.replace(r"\linenumbers", "").lstrip("\n")
    body = body.replace(r"\bibliographystyle{elsarticle-harv}",
                        r"\bibliographystyle{plainnat}")
    assert r"\bibliographystyle{plainnat}" in body, "bibliography style not set"
    assert r"\clearpage" not in body and r"\newpage" not in body, \
        "the guide forbids page breaks in the manuscript"

    io.open(OUT, "w", encoding="utf-8").write(PREAMBLE + frontmatter(tex) + body)

    # an aux left by another class defines commands this one does not
    subprocess.run(["latexmk", "-C", STEM], cwd="paper_or",
                   capture_output=True, text=True)
    for _ in range(3):
        subprocess.run(["latexmk", "-pdf", "-interaction=nonstopmode", STEM],
                       cwd="paper_or", capture_output=True, text=True)

    pdf = f"paper_or/{STEM}.pdf"
    if not os.path.exists(pdf):
        print(f"{STEM}.pdf did not build; see paper_or/{STEM}.log")
        return 1

    log = io.open(f"paper_or/{STEM}.log", encoding="utf-8",
                  errors="replace").read()
    for bad in ("multiply defined", "There were undefined references",
                "Undefined control sequence"):
        if bad in log:
            print(f"{STEM}.log reports: {bad}")
            return 1

    import fitz
    d = fitz.open(pdf)
    txt = "\n".join(p.get_text() for p in d)
    refs = next((i + 1 for i, p in enumerate(d)
                 if re.search(r"\nReferences", p.get_text())), None)
    os.makedirs("out/or", exist_ok=True)
    io.open("out/or/fininnov_text.txt", "w", encoding="utf-8").write(txt)
    print(f"wrote {OUT} and {pdf}")
    print(f"PAGES: {d.page_count}   references begin on page {refs}")
    words = len(re.findall(r"[A-Za-z][A-Za-z'-]+", txt))
    print(f"about {words} words of body text including references")
    return 0


if __name__ == "__main__":
    sys.exit(main())
