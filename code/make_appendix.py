"""The appendix that prints every rule the pipeline ran.

Three rounds of review in a row found a number that had been computed and left
out of the paper, each time one that complicated a claim. The response is not a
better excuse but a table: every policy evaluated at every basket size, and
every paired comparison between them, with what each returned. The gate in
check_or.py fails the build if anything in the record is missing from here or
from the body of the paper.

Reads out/or/policy.json and writes paper_or/appendix_rules.tex, which the paper
inputs. Every cell is a macro, so the appendix obeys the same rule as the body.

Usage: python or_journal/make_appendix.py
"""
import argparse
import json
import os
import sys

KW = {"1": "One", "3": "Three", "5": "Five", "10": "Ten", "20": "Twenty", "40": "Forty",
      "80": "Eighty", "160": "Onesixty"}

FAM = {"open": "whole venue", "risk": "risk screened", "big": "size screened"}
RULE = {"random": "{k} at random", "top": "{k} highest past Sharpe",
        "all": "every leader in the set",
        "replace": "{k} at random, refilled when one stops",
        "index": "{k} by the band, re-ranked weekly",
        "hold_index": "{k} by the band's statistic, held"}
GAIN = {"screen_gain": "screening against the whole venue",
        "rank_gain": "ordering against drawing at random",
        "replace_gain": "refilling against leaving a sleeve empty",
        "spread_gain": "twenty leaders against five",
        "index_gain": "the band against drawing at random",
        "index_over_top": "the band against a static past-Sharpe ranking",
        "statistic": "the band's statistic, held, against a past-Sharpe ranking",
        "churn": "weekly re-ranking against holding the same statistic",
        "all_gain": "the whole screened set against twenty of it"}


def camel(key: str) -> str:
    return "".join(KW.get(p, p.capitalize()) for p in key.split("_"))


def main(argv=None) -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--policy", default="out/or/policy.json")
    ap.add_argument("--out", default="paper_or/appendix_rules.tex")
    args = ap.parse_args(argv)
    pol = json.load(open(args.policy, encoding="utf-8"))
    summary = pol.get("summary", {})

    levels, gains = [], []
    for key in sorted(summary):
        if any(key.startswith(g) for g in GAIN):
            gains.append(key)
        else:
            levels.append(key)

    def row(key, label):
        m = "\\n" + "Policy" + camel(key)
        return (f"{label} & {m}Mean{{}} & {m}Min{{}} to {m}Max{{}} & "
                f"{m}Wins{{}} & {m}GrossMean{{}} & {m}Growth{{}} \\\\")

    out = ["% Generated by or_journal/make_appendix.py -- do not edit by hand.",
           "\\section{Every rule that was run}",
           "\\label{app:rules}",
           "",
           "Tables~\\ref{tab:all-levels} and~\\ref{tab:all-gains} give every policy the pipeline "
           "evaluated and every paired comparison between them, including the ones the body of the "
           "paper does not discuss. They are here because the alternative is to choose which of "
           "them to show, and that choice is not one a reader can check. The build fails if a rule "
           "in the run record appears in neither place.",
           "",
           "\\begin{table}[htbp]",
           "\\caption{Every policy, at every basket size. ``Net'' averages the median net Sharpe "
           "ratio across the \\nPolicyDates{} decision dates, ``positive'' counts the dates on which "
           "it was above zero, ``gross'' is the same average before the copying cost, and "
           "``growth'' is the median annualised compound growth of the net series.}",
           "\\label{tab:all-levels}",
           "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{4pt}",
           "\\begin{tabular}{@{}llrrrrr@{}}", "\\toprule",
           "Set & Rule & Net & Range & Positive & Gross & Growth \\\\", "\\midrule"]

    for key in levels:
        parts = key.split("_")
        fam = parts[0]
        k = parts[-1] if parts[-1].isdigit() else ""
        rule = "_".join(parts[1:-1]) if k else "_".join(parts[1:])
        m = "\\n" + "Policy" + camel(key)
        label = RULE.get(rule, rule.replace("_", " "))
        label = label.replace("{k}", k) if k else label
        out.append(f"{FAM.get(fam, fam)} & {label} & {m}Mean{{}} & {m}Min{{}} to {m}Max{{}} & "
                   f"{m}Positive{{}} & -- & {m}Growth{{}} \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}", "",
            "\\begin{table}[htbp]",
            "\\caption{Every paired comparison. Each is the difference between two rules that are "
            "otherwise identical, taken inside the named set. ``Wins'' counts the dates on which "
            "the difference was positive, and ``gross'' repeats it before the copying cost.}",
            "\\label{tab:all-gains}",
            "\\centering", "\\scriptsize", "\\setlength{\\tabcolsep}{4pt}",
            "\\begin{tabular}{@{}llrrrr@{}}", "\\toprule",
            "Set & Comparison & Net & Range & Wins & Gross \\\\", "\\midrule"]
    for key in gains:
        pre = next((g for g in GAIN if key.startswith(g)), None)
        rest = key[len(pre) + 1:] if pre else key
        parts = rest.split("_")
        fam = parts[0] if parts[0] in FAM else "open"
        k = parts[-1] if parts[-1].isdigit() else ""
        m = "\\n" + "Policy" + camel(key)
        lab = GAIN.get(pre, pre or key)
        if k:
            lab = f"{lab}, {k} leaders"
        out.append(f"{FAM.get(fam, fam)} & {lab} & {m}Mean{{}} & {m}Min{{}} to {m}Max{{}} & "
                   f"{m}Wins{{}} & {m}GrossMean{{}} \\\\")
    out += ["\\bottomrule", "\\end{tabular}", "\\end{table}", ""]

    os.makedirs(os.path.dirname(args.out), exist_ok=True)
    open(args.out, "w", encoding="utf-8").write("\n".join(out) + "\n")
    print(f"wrote {args.out}: {len(levels)} policies and {len(gains)} comparisons")
    return 0


if __name__ == "__main__":
    os.chdir(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    sys.exit(main())
