def write_captions(src_dir: str) -> int:
    """The separate list of captions the guide requires.

    "A list of captions to the illustrations, including source information,
    should be supplied separately from the text." It is generated from the
    captions themselves so the two cannot disagree, and it names the run record
    each figure was drawn from, which is the source information that matters
    here: no figure is reproduced from anywhere, so nothing needs permission.
    """
    SRC = {"fig_survival": "out/or/facts.json (attrition)",
           "fig_signal": "out/or/facts.json (rank correlation)",
           "fig_dependence": "out/or/facts.json (dependence, baskets)",
           "fig_surface": "out/or/facts.json (decision surface)",
           "fig_cost": "out/or/facts.json (cost grid)",
           "fig_gains": "out/or/policy.json (rule comparisons)",
           "fig_band": "out/or/theory.json (solved boundary)"}
    rows = []
    for doc in ("main.tex", "supplement.tex"):
        t = io.open(os.path.join(src_dir, doc), encoding="utf-8").read()
        for m in re.finditer(
                r"\\includegraphics\[[^\]]*\]\{figures/(\w+)(?:\.pdf)?\}(.*?)\\label\{(fig:[^}]+)\}",
                t, re.S):
            key, mid, lab = m.group(1), m.group(2), m.group(3)
            cap = re.search(r"\\caption\{(.*?)\}\s*\n", mid, re.S)
            text = re.sub(r"\s+", " ", cap.group(1)) if cap else ""
            text = re.sub(r"\\n[A-Za-z]+\{\}", "[value]", text)
            text = re.sub(r"\\[a-zA-Z]+\{?|\}", "", text)
            rows.append((doc, key, lab, text.strip()))
    out = ["List of captions to the illustrations", "",
           "Every figure is line art generated by or_journal/figures.py from the run",
           "record named beside it; none is reproduced from another source, so no",
           "copyright permission is required. High-resolution EPS files are supplied",
           "separately as figures/<name>.eps. Values shown as [value] are LaTeX macros",
           "generated from the run record and appear as numbers in the PDF.", ""]
    for i, (doc, key, lab, text) in enumerate(rows, 1):
        where = "manuscript" if doc == "main.tex" else "supplement"
        out += [f"{i}. {key}.eps  ({where}, {lab})",
                f"   Source: {SRC.get(key, 'see or_journal/figures.py')}",
                f"   Caption: {text}", ""]
    io.open(os.path.join(src_dir, "figure_captions.txt"), "w",
            encoding="utf-8").write("\n".join(out))
    return len(rows)


