"""Assemble everything the portal asks for into one folder, with a checklist.

The guide names more files than a manuscript: high-resolution figures in
separate files, a list of captions supplied apart from the text, a cover letter,
and the supplement. Collecting them by hand at the portal is how one gets
forgotten, so they are collected here, and the checklist states what goes in
which field rather than leaving it to memory at the upload screen.

Nothing here is generated: every file is copied from what the gate has already
checked, so the folder cannot contain a version the gate has not seen.
"""
